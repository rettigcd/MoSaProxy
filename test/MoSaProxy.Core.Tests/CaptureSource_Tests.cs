using System.IO.Compression;
using System.Net;
using System.Net.Sockets;
using System.Text;
using System.Xml.Linq;
using Microsoft.AspNetCore.Http;
using Shouldly;

namespace MoSaProxy.Tests;

/// <summary>Each exchange's metadata says where its request and response files came from (<see cref="CaptureSource"/>).</summary>
public class CaptureSource_Tests {

	static byte[] B(string text) => Encoding.Latin1.GetBytes(text);

	static ProxyOptions Capturing(TempFolder folder) => new() {
		Port = 0, CaptureDirectory = folder.Path,
		Intercept = true, CaDirectory = Path.Combine(folder.Path, "ca"), OriginCertificateValidation = (_, _, _, _) => true,
	};

	static async Task<XElement> MetadataAsync(TestProxy proxy, int number) {
		string path = Path.Combine(proxy.CaptureRunDirectory!, $"{number}_m.xml");
		await TempFolder.WaitForFileAsync(path);
		return XDocument.Load(path).Root!;
	}

	/// <summary>Sends one request line plus headers on a new connection and waits for the proxy to answer.</summary>
	static async Task SendAndWaitAsync(int port, string request) {
		using var tcp = new TcpClient();
		await tcp.ConnectAsync(IPAddress.Loopback, port);
		var stream = tcp.GetStream();
		await stream.WriteAsync(B(request));
		using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(10));
		await stream.ReadAsync(new byte[4096], timeout.Token);
	}

	[Fact]
	public async Task Http1Exchange_BothFilesAreFromTheWire() {

		// Given: a raw HTTP/1.1 origin and a capturing proxy
		using var folder = new TempFolder();
		await using var origin = RawOrigin.Start(_ => B("HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\nok"));
		await using var proxy = await TestProxy.StartAsync(Capturing(folder));

		// When: a request goes through the proxy
		await SendAndWaitAsync(proxy.Port, $"GET http://127.0.0.1:{origin.Port}/x HTTP/1.1\r\nHost: 127.0.0.1:{origin.Port}\r\n\r\n");

		// Then: the metadata says both files hold the exact wire bytes
		var meta = await MetadataAsync(proxy, 1);
		meta.Element("RequestSource")!.Value.ShouldBe(CaptureSource.Wire);
		meta.Element("ResponseSource")!.Value.ShouldBe(CaptureSource.Wire);
	}

	[Fact]
	public async Task Http2Exchange_BothFilesAreParsed() {

		// Given: an HTTP/2 origin and an intercepting, capturing proxy
		using var folder = new TempFolder();
		await using var origin = await TestOrigin.StartAsync(c => c.Response.WriteAsync("hi"), https: true);
		await using var proxy = await TestProxy.StartAsync(Capturing(folder));
		proxy.AlsoTrust.Add(origin.Certificate!.Thumbprint);

		// When: a client requests a page over HTTP/2
		(await proxy.Http2Client.GetAsync(origin.UrlFor("/h2"))).Version.ShouldBe(HttpVersion.Version20);

		// Then: the files were written from parsed data (exchange 2; exchange 1 is the CONNECT)
		var meta = await MetadataAsync(proxy, 2);
		meta.Element("RequestSource")!.Value.ShouldBe(CaptureSource.Parsed);
		meta.Element("ResponseSource")!.Value.ShouldBe(CaptureSource.Parsed);
	}

	[Fact]
	public async Task OriginUnreachable_ResponseIsGeneratedAndRequestIsFromTheWire() {

		// Given: a capturing proxy and a port where nothing is listening
		using var folder = new TempFolder();
		await using var proxy = await TestProxy.StartAsync(Capturing(folder));
		int deadPort;
		using (var probe = new TcpListener(IPAddress.Loopback, 0)) {
			probe.Start();
			deadPort = ((IPEndPoint)probe.LocalEndpoint).Port;
		}

		// When: a request for that port goes through the proxy, which answers 502 itself
		await SendAndWaitAsync(proxy.Port, $"GET http://127.0.0.1:{deadPort}/ HTTP/1.1\r\nHost: 127.0.0.1:{deadPort}\r\n\r\n");

		// Then: the response file is marked as generated by the proxy, and the request is still the client's exact bytes
		var meta = await MetadataAsync(proxy, 1);
		meta.Element("ResponseSource")!.Value.ShouldBe(CaptureSource.Generated);
		meta.Element("RequestSource")!.Value.ShouldBe(CaptureSource.Wire);
	}

	[Fact]
	public async Task Export_CarriesTheSourcesIntoTheSessionFlags() {

		// Given: a captured HTTP/1.1 exchange
		using var folder = new TempFolder();
		await using var origin = RawOrigin.Start(_ => B("HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\nok"));
		string run;
		await using (var proxy = await TestProxy.StartAsync(Capturing(folder))) {
			await SendAndWaitAsync(proxy.Port, $"GET http://127.0.0.1:{origin.Port}/x HTTP/1.1\r\nHost: 127.0.0.1:{origin.Port}\r\n\r\n");
			await MetadataAsync(proxy, 1);
			run = proxy.CaptureRunDirectory!;
		}
		string saz = Path.Combine(folder.Path, "sources.saz");

		// When: the run folder is exported
		SazExporter.Export(run, saz);

		// Then: the session has x-mosaproxy-request-source and x-mosaproxy-response-source flags saying "wire"
		using var zip = ZipFile.OpenRead(saz);
		using var stream = zip.GetEntry("raw/1_m.xml")!.Open();
		var flags = XDocument.Load(stream).Root!.Element("SessionFlags")!.Elements("SessionFlag").ToDictionary(f => f.Attribute("N")!.Value, f => f.Attribute("V")!.Value);
		flags["x-mosaproxy-request-source"].ShouldBe(CaptureSource.Wire);
		flags["x-mosaproxy-response-source"].ShouldBe(CaptureSource.Wire);
	}
}
